import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx=vm.createContext({});vm.runInContext(fs.readFileSync('lessons.js','utf8')+';globalThis.lessonsData=lessons;',ctx);
const lesson=id=>ctx.lessonsData.find(l=>l.id===id);
const text=id=>lesson(id).deep.flatMap(s=>s.paragraphs).join(' ').replaceAll(',', '').replaceAll('−', '-');
const table=id=>lesson(id).deep[1].table;
const near=(actual,expected,tolerance)=>assert(Math.abs(Number(actual)-expected)<=tolerance,`${actual} vs ${expected}`);
const bondPrice=5/1.06+105/1.06**2;
near(table(5).rows[2][2],bondPrice,.00001);
const dcf=(r,g)=>10/(1+r)+12/(1+r)**2+(14+14*(1+g)/(r-g))/(1+r)**3;
for(const [i,r] of [.09,.10,.11].entries())for(const [j,g] of [.01,.02,.03].entries())near(table(18).rows[i][j+1],dcf(r,g),.005);
assert(text(17).includes(((281724-87831)/281724*100).toFixed(4)),'real-report gross margin');
assert(text(17).includes((128528/281724*100).toFixed(4)),'real-report operating margin');
assert(text(3).includes((10000*(1.05*.99)**3).toFixed(2)),'fee-adjusted nominal value');
const taxNet=10000+(10000*(1.05*.99)**3-10000)*.8;
assert(text(3).includes(taxNet.toFixed(2)),'hypothetical terminal tax');
assert(text(3).includes((taxNet/(1.02*1.03*1.04)).toFixed(2)),'three-year purchasing power');
near(table(14).rows[0][4],10000*1.11*.85,.000001);
near(table(14).rows[1][4],10000*1.14*.8,.000001);
near(table(14).rows[2][4],10000*1.17*.75,.000001);
assert(text(10).includes((((-1+Math.sqrt(8.92))/2-1)*100).toFixed(4)),'IRR root');
